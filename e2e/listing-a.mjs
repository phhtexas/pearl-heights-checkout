// Listing option A: renders, dates → total → Reserve hands off to Checkout E with dates and guests.
// Run: ALLOW_MOCK=true npx next start -p 3401 ; BASE_URL=http://localhost:3401 node e2e/listing-a.mjs [shotsDir]
import { createRequire } from "node:module";
const { chromium, devices } = createRequire(import.meta.url)("playwright");
const BASE = process.env.BASE_URL ?? "http://localhost:3401";
const SHOTS = process.argv[2];
const ok = (c, m) => { console.log((c ? "ok  - " : "FAIL- ") + m); if (!c) process.exitCode = 1; };
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 13"] });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`${BASE}/homes/736-myrtle/a`);
await page.waitForSelector("h1");
ok((await page.textContent("h1")) === "Large Family House Next to the Pearl", "title is the 736 title");
ok((await page.locator(".A-dots span").count()) === 5, "five hero dots");
ok((await page.textContent(".A-count")) === "1 / 71", "photo counter shows 1 / 71");
await page.click(".A-count");
await page.waitForSelector(".A-tour");
const groups = await page.locator(".A-tourSec").count(), pics = await page.locator(".A-tourPh").count();
ok(groups >= 8 && pics === 71, `photo tour opens with every photo grouped by room (${groups} groups, ${pics} photos)`);
if (SHOTS) await page.screenshot({ path: `${SHOTS}/a-tour.png` });
await page.click('[aria-label="Back to the listing"]');
ok((await page.locator(".A-tour").count()) === 0, "back arrow closes the tour");
ok((await page.locator(".A-room").count()) === 6, "six sleeping cards with photos");
ok(!/example|no platform fees|Verified local/i.test(await page.textContent("body")), "no example tags or unsourced claims");
await page.waitForTimeout(1500);
if (SHOTS) await page.screenshot({ path: `${SHOTS}/a-first.png`, fullPage: true });
await page.click(".A-bar .A-cta");
await page.waitForSelector(".day:not([disabled])");
for (let i = 0; i < 6 && !(await page.locator('[aria-label^="Sun, Jan 10, 2027"]').count()); i++) await page.click('[aria-label="Next month"]');
await page.click('[aria-label^="Sun, Jan 10, 2027"]');
await page.click('[aria-label^="Tue, Jan 12, 2027"]');
await page.click("text=Save dates");
await page.waitForSelector(".A-bar b:has-text('total')", { timeout: 10000 });
ok(/Jan 10–12/.test(await page.textContent(".A-barLinks")), "bar shows the dates");
await page.click(".A-barLinks button:nth-of-type(2)");
await page.click('[aria-label="More Children"]');
await page.click("text=Save guests");
await page.waitForSelector(".A-bar b:has-text('total')", { timeout: 10000 });
if (SHOTS) await page.screenshot({ path: `${SHOTS}/a-quote.png` });
await page.click(".A-bar .A-cta");
await page.waitForURL(/checkIn=2027-01-10/);
ok(/checkOut=2027-01-12&adults=2&children=1&infants=0/.test(page.url()), "Reserve hands off dates and guests to checkout");
const ev = await page.evaluate(() => 1);
ok(errors.length === 0, "no page errors " + errors.join(" | "));
await browser.close();
